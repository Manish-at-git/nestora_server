@lru_cache
def load_iam_seed_snapshot() -> dict[str, list[dict[str, Any]]]:
    """Return copied role, feature, and permission rows without external I/O."""
    payload = json.loads(
        gzip.decompress(base64.b85decode("".join(_COMPRESSED_SNAPSHOT))).decode("utf-8")
    )
    for group in ("roles", "features", "permissions"):
        for row in payload[group]:
            created_at = row.get("created_at")
            if created_at:
                row["created_at"] = datetime.fromisoformat(created_at)
    return payload

